// Compiles contracts/TokenizedDeposit.sol with solc-js and writes the ABI +
// bytecode to lib/chain/artifact.ts, so neither the app nor Vercel needs Foundry.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import solc from "solc";

const root = join(import.meta.dirname, "..");
const file = "TokenizedDeposit.sol";
const source = readFileSync(join(root, "contracts", file), "utf8");

const input = {
  language: "Solidity",
  sources: { [file]: { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
if (errors.length) {
  console.error(errors.map((e: { formattedMessage: string }) => e.formattedMessage).join("\n"));
  process.exit(1);
}

const c = output.contracts[file].TokenizedDeposit;
const out = `// AUTO-GENERATED by scripts/compile.ts (solc ${solc.version()}). Do not edit.
export const depositTokenAbi = ${JSON.stringify(c.abi, null, 2)} as const;

export const depositTokenBytecode = "0x${c.evm.bytecode.object}" as const;
`;
writeFileSync(join(root, "lib", "chain", "artifact.ts"), out);
console.log(`compiled ${file} with solc ${solc.version()} -> lib/chain/artifact.ts`);
