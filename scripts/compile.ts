// Compiles the contracts in contracts/ with solc-js and writes ABIs + bytecode to
// lib/chain/artifact.ts, so neither the app nor Vercel needs Foundry.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import solc from "solc";

const root = join(import.meta.dirname, "..");
const dir = join(root, "contracts");
const sources = Object.fromEntries(
  readdirSync(dir)
    .filter((f) => f.endsWith(".sol"))
    .map((f) => [f, { content: readFileSync(join(dir, f), "utf8") }]),
);

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
if (errors.length) {
  console.error(errors.map((e: { formattedMessage: string }) => e.formattedMessage).join("\n"));
  process.exit(1);
}

// contract name in the .sol file -> exported identifier prefix
const targets: [file: string, contract: string, id: string][] = [
  ["TokenizedDeposit.sol", "TokenizedDeposit", "depositToken"],
  ["BondToken.sol", "BondToken", "bondToken"],
  ["DvPSettlement.sol", "DvPSettlement", "dvpSettlement"],
  ["SettlementAnchor.sol", "SettlementAnchor", "settlementAnchor"],
];

let out = `// AUTO-GENERATED by scripts/compile.ts (solc ${solc.version()}). Do not edit.\n`;
for (const [file, contract, id] of targets) {
  const c = output.contracts[file][contract];
  out += `
export const ${id}Abi = ${JSON.stringify(c.abi, null, 2)} as const;

export const ${id}Bytecode = "0x${c.evm.bytecode.object}" as const;
`;
}
writeFileSync(join(root, "lib", "chain", "artifact.ts"), out);
console.log(`compiled ${targets.map((t) => t[1]).join(", ")} with solc ${solc.version()} -> lib/chain/artifact.ts`);
